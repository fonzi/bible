/// A passage for a feast or holy day, if this date has one.
fn for_feast(date: NaiveDate) -> Option<(&'static str, &'static str)> {
    let (m, d) = (date.month(), date.day());
    let easter = easter_western(date.year());
    let off = (date - easter).num_days();
    Some(match (m, d, off) {
        (12, 24, _) => ("Christmas Eve", "Isa.9.6-Isa.9.7"),
        (12, 25, _) => ("Christmas Day", "Luke.2.8-Luke.2.14"),
        (1, 1, _) => ("New Year’s Day", "Lam.3.22-Lam.3.24"),
        (1, 6, _) => ("Epiphany", "Matt.2.1-Matt.2.11"),
        (_, _, -46) => ("Ash Wednesday", "Joel.2.12-Joel.2.13"),
        (_, _, -7) => ("Palm Sunday", "Zech.9.9"),
        (_, _, -3) => ("Maundy Thursday", "John.13.12-John.13.15"),
        (_, _, -2) => ("Good Friday", "Isa.53.3-Isa.53.6"),
        (_, _, -1) => ("Holy Saturday", "Matt.27.57-Matt.27.61"),
        (_, _, 0) => ("Easter Day", "Matt.28.1-Matt.28.7"),
        (_, _, 39) => ("Ascension Day", "Acts.1.8-Acts.1.11"),
        (_, _, 49) => ("Pentecost", "Acts.2.1-Acts.2.4"),
        (_, _, 56) => ("Trinity Sunday", "Matt.28.18-Matt.28.20"),
        (10, 31, _) => ("Reformation Day", "Rom.1.16-Rom.1.17"),
        (11, 1, _) => ("All Saints’ Day", "Heb.12.1-Heb.12.2"),
        _ => return None,
    })
}

/// (occasion if any, OSIS range) for a date. Same passage for everyone on a day.
pub fn passage(date: NaiveDate, _t: Tradition) -> (Option<&'static str>, &'static str) {
    if let Some((name, p)) = for_feast(date) {
        return (Some(name), p);
    }
    let i = (date.num_days_from_ce() as usize) % PASSAGES.len();
    (None, PASSAGES[i])
}

/// (book, chapter, first verse, last verse) of a single-chapter range.
pub fn verses(osis: &str) -> Option<(String, u16, u16, u16)> {
    let r = crate::refs::parse_osis(osis.split('-').next()?)?;
    let end = osis
        .split('-')
        .nth(1)
        .and_then(crate::refs::parse_osis)
        .map(|e| e.verse)
        .unwrap_or(r.verse);
    Some((r.book, r.chapter, r.verse, end.max(r.verse)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_passage_parses() {
        assert!(PASSAGES.len() >= 365, "{}", PASSAGES.len());
        for p in PASSAGES {
            let (b, c, v0, v1) = verses(p).unwrap_or_else(|| panic!("{p}"));
            assert!(v1 >= v0 && v1 - v0 < 25, "{p}");
            assert!(crate::v11n::kjv().book(&b).is_some(), "{p}");
            assert!(c > 0);
        }
        let mut seen = std::collections::HashSet::new();
        for p in PASSAGES {
            assert!(seen.insert(*p), "duplicate {p}");
        }
        let xmas = NaiveDate::from_ymd_opt(2026, 12, 25).unwrap();
        assert_eq!(passage(xmas, Tradition::Western).0, Some("Christmas Day"));
        assert_eq!(
            passage(
                NaiveDate::from_ymd_opt(2026, 4, 5).unwrap(),
                Tradition::Western
            )
            .0,
            Some("Easter Day")
        );
    }
}
